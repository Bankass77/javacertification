package org.example.java17.chapter8.functions;

public class Customer {
    String name;
    String phoneNum;
    String sport;
    String team;
    double gpa;
    String subject;
    int numFriends;
    String friends;

    public Customer(final String name, final String phoneNum, final String sport, final String team, final double gpa, final String subject, final int numFriends, final String friends) {
        this.name = name;
        this.phoneNum = phoneNum;
        this.sport = sport;
        this.team = team;
        this.gpa = gpa;
        this.subject = subject;
        this.numFriends = numFriends;
        this.friends = friends;
    }


}
